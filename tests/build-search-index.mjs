// Generates assets/js/search-index.js from the site's own HTML pages.
// Source of truth: <title>, meta description, <h1> and the page's folder path.
// Run: node tests/build-search-index.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

const ROOT = process.cwd();
const OUTPUT = join(ROOT, "assets", "js", "search-index.js");
const SKIP = new Set([".git", ".vscode", "node_modules", "reports", "tests", "downloads", "assets"]);

const decode = (s) =>
  s
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&nbsp;/g, " ")
    .replace(/&rarr;/g, "→")
    .replace(/&mdash;/g, "—")
    .replace(/&ndash;/g, "–")
    .replace(/\s+/g, " ")
    .trim();

const stripTags = (s) => decode(s.replace(/<[^>]+>/g, ""));

const pages = [];
(function walk(dir) {
  for (const entry of readdirSync(dir)) {
    if (SKIP.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full);
    else if (entry === "index.html") pages.push(full);
  }
})(ROOT);

// Category + type derived from the folder path so results can be grouped.
const classify = (routePath) => {
  const parts = routePath.split("/").filter(Boolean);
  const top = parts[0] || "";
  if (routePath === "/") return { category: "Home", type: "Page" };
  if (top === "categories") {
    const hub = parts[1] || "";
    return { category: cap(hub), type: parts.length > 2 ? "Tool" : "Category" };
  }
  if (top === "templates") {
    const hub = parts[1] || "";
    return { category: hub ? cap(hub) + " Templates" : "Templates", type: "Template" };
  }
  if (top === "guides") return { category: "Guides", type: parts.length > 1 ? "Guide" : "Category" };
  if (top === "inventory") return { category: "Inventory", type: "Tool" };
  if (top === "logistics") return { category: "Logistics", type: "Tool" };
  if (top === "simulators") return { category: "Simulators", type: "Tool" };
  if (top === "about" || top === "contact" || top === "privacy" || top === "terms")
    return { category: "Company", type: "Page" };
  if (top === "ai-operations-assistant" || top === "inventory-control-toolkit")
    return { category: "Inventory", type: "Page" };
  return { category: "Other", type: "Page" };
};

const cap = (s) => (s ? s.charAt(0).toUpperCase() + s.slice(1) : s);

const prettyTitle = (file, routePath) => {
  const parts = routePath.split("/").filter(Boolean);
  if (routePath === "/") return "DIXANI Home";
  const slug = parts[parts.length - 1] || "";
  return cap(slug.replace(/-/g, " "));
};

const entries = [];
for (const file of pages) {
  const html = readFileSync(file, "utf8");
  let route = "/" + relative(ROOT, file).split(sep).join("/").replace(/index\.html$/, "");
  const title = decode((html.match(/<title[^>]*>([\s\S]*?)<\/title>/i) || [])[1] || "");
  const descTag = html.match(/<meta[^>]*name=["']description["'][^>]*>/i);
  const desc = descTag ? decode((descTag[0].match(/content=["']([\s\S]*?)["']/i) || [])[1] || "") : "";
  const h1 = stripTags((html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i) || [])[1] || "");
  const { category, type } = classify(route);

  // Visible title without the trailing "| DIXANI" brand suffix.
  const cleanTitle = title.replace(/\s*\|\s*DIXANI\s*$/, "").trim() || prettyTitle(file, route);

  entries.push({ url: route, title: cleanTitle, h1, category, type, description: desc });
}

entries.sort((a, b) => a.url.localeCompare(b.url));

const payload = entries.map((e) => {
  // Only keep the description if it adds information beyond the title/h1.
  const extra = e.description && e.description !== e.title && e.description !== e.h1 ? e.description : "";
  const row = { u: e.url, t: e.title, c: e.category, y: e.type };
  if (extra) row.d = extra;
  return row;
});

const out = `/* Generated by tests/build-search-index.mjs — do not edit by hand. */\nwindow.DIXANI_SEARCH_INDEX = ${JSON.stringify(payload)};\n`;
writeFileSync(OUTPUT, out, "utf8");
console.log(`Wrote ${payload.length} entries to assets/js/search-index.js`);
